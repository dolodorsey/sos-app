import test from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import { execSync } from 'node:child_process'
const read = p => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8')

test('every icon is generated from the official S.O.S. shield logo', () => {
  const gen = read('scripts/brand-icons.py')
  assert.match(gen, /SRC = 'public\/brand\/sos-logo\.webp'/)
  for (const f of ['public/favicon.png', 'public/favicon.ico', 'public/apple-touch-icon.png', 'public/sos-app-icon-192.png', 'public/sos-app-icon-512.png', 'public/sos-app-icon-512-maskable.png', 'AppIcon-1024.png', 'ios/App/App/Assets.xcassets/AppIcon.appiconset/SOS.png'])
    assert.ok(gen.includes(f.replace(/^.*AppIcon\.appiconset\/SOS\.png$/, 'AppIcon.appiconset')), `${f} is regenerated by the script`)
  assert.match(read('android/app/src/main/res/values/ic_launcher_background.xml'), /#05080D/)
})

test('no old logos left: no Kollective favicon, tire icon or emoji stand-in', () => {
  assert.doesNotMatch(read('src/app/download/page.tsx'), /📱/)
  assert.match(read('src/app/download/page.tsx'), /\/brand\/sos-logo\.webp/)
  const svg = read('public/sos-icon-192.svg')
  assert.doesNotMatch(svg, /radialGradient id="bg"/, 'old hand-drawn red SOS square is gone')
})
